#!/bin/bash
# Build "Website Editor.app" — a Mac app for the editor that you can keep in the Dock.
#
#   bash _editor/make_app.sh            # installs to ~/Applications/Website Editor.app
#   bash _editor/make_app.sh /some/dir  # or somewhere else
#
# The app starts the editor server in the background and opens it in your browser.
# While it runs it shows in the Dock; clicking the Dock icon reopens the editor tab,
# and quitting the app (⌘Q or Dock → Quit) stops the server.
# Run this again if you move the website folder or switch Python.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST_DIR="${1:-$HOME/Applications}"
APP="$DEST_DIR/Website Editor.app"
ICON_SRC="$ROOT/assets/images/favicon-512.png"
LOG="$HOME/Library/Logs/Website Editor.log"
URL_FILE="$HOME/Library/Caches/website-editor-url.txt"

# Same python3 you get in Terminal (apps don't see your shell PATH).
PY="$(/bin/bash -lc 'command -v python3' 2>/dev/null | tail -n 1 || true)"
[ -x "$PY" ] || PY=/usr/bin/python3
"$PY" -c 'import sys; assert sys.version_info >= (3, 8)' || { echo "Need Python 3.8+ ($PY)"; exit 1; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

cat > "$WORK/app.applescript" <<APPLESCRIPT
-- Generated by _editor/make_app.sh — edit that script, not this.
global serverPid, editorURL

on run
	set serverPid to ""
	set editorURL to ""
	startEditor()
end run

-- Clicking the Dock icon while running: bring the editor back.
on reopen
	if editorURL is "" then
		startEditor()
	else
		open location editorURL
	end if
end reopen

on startEditor()
	set root to "$ROOT"
	set urlFile to "$URL_FILE"
	set logFile to "$LOG"
	do shell script "rm -f " & quoted form of urlFile
	-- "cd ... || exit; nohup ... &" (not "cd && nohup &") so only the server is backgrounded,
	-- with every stream redirected; otherwise do shell script waits forever and Quit hangs.
	set serverPid to do shell script "cd " & quoted form of root & " || exit 1; nohup " & quoted form of "$PY" & " _editor/editor.py --no-browser --url-file " & quoted form of urlFile & " > " & quoted form of logFile & " 2>&1 < /dev/null & echo \$!"
	repeat 50 times
		try
			set editorURL to do shell script "cat " & quoted form of urlFile
			exit repeat
		end try
		delay 0.2
	end repeat
	if editorURL is "" then
		set details to do shell script "tail -n 15 " & quoted form of logFile & " 2>/dev/null || true"
		display alert "Website Editor didn't start" message details as critical
		stopServer()
		quit
	else
		open location editorURL
	end if
end startEditor

on stopServer()
	if serverPid is not "" then
		do shell script "kill " & serverPid & " 2>/dev/null || true"
		set serverPid to ""
	end if
end stopServer

on quit
	stopServer()
	continue quit
end quit
APPLESCRIPT

mkdir -p "$DEST_DIR" "$(dirname "$LOG")" "$(dirname "$URL_FILE")"
rm -rf "$APP"
osacompile -s -o "$APP" "$WORK/app.applescript"   # -s: stay open (lives in the Dock)

# App name and identity
PLIST="$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleName Website Editor" "$PLIST"
/usr/libexec/PlistBuddy -c "Add :CFBundleDisplayName string Website Editor" "$PLIST" 2>/dev/null || true
/usr/libexec/PlistBuddy -c "Add :CFBundleIdentifier string io.github.leotsukada.website-editor" "$PLIST" 2>/dev/null \
  || /usr/libexec/PlistBuddy -c "Set :CFBundleIdentifier io.github.leotsukada.website-editor" "$PLIST"

# Icon from the site's logo
if [ -f "$ICON_SRC" ]; then
  SET="$WORK/icon.iconset"; mkdir "$SET"
  for s in 16 32 128 256 512; do
    sips -z $s $s "$ICON_SRC" --out "$SET/icon_${s}x${s}.png" >/dev/null
    d=$((s * 2)); [ $d -le 512 ] && sips -z $d $d "$ICON_SRC" --out "$SET/icon_${s}x${s}@2x.png" >/dev/null
  done
  cp "$ICON_SRC" "$SET/icon_512x512@2x.png"
  iconutil -c icns "$SET" -o "$APP/Contents/Resources/applet.icns"
  rm -f "$APP/Contents/Resources/Assets.car"   # newer osacompile uses this instead of applet.icns
fi

codesign --force --deep -s - "$APP" 2>/dev/null || true   # re-sign after changing the bundle
touch "$APP"
echo "Built: $APP"
echo "Open it once, then right-click its Dock icon → Options → Keep in Dock."
